# =====================================================================
# KSHS CAMPUS PLOTS - Minecraft Education build script (MakeCode Python)
# Builds Kelmscott SHS (from the Robot Lab campus map) with 12 fenced
# team plots. Students can only build inside their plot.
#
# HOW TO RUN (teacher, once per world):
#  1. Create a NEW world: Flat, Creative, Cheats ON. Do not host yet.
#  2. Stand on the ground (not flying). Press C -> MakeCode -> New Project.
#  3. Click the Python tab, delete everything, paste this whole file.
#  4. Click the green Play button, go back to the game, press T and type:
#         campus
#     Wait until the chat says "Campus finished" (about 2-4 minutes).
#     The school is built around world position 0,0 (Main Entry).
#     Type campus ONLY ONCE per world - running it again wipes every plot.
#  5. Next lesson: open the world, press C, click Play on this project
#     again, stand on the ground and use the commands below.
#
# OTHER CHAT COMMANDS (type in chat with T):
#   plot 3      teleport yourself to plot 3
#   gather      teleport everyone to the Main Entry
#   clear 3     wipe plot 3 back to empty grass (use between classes)
#   lock        students can only build in plots (default after build)
#   unlock      students can build anywhere (careful!)
#   walls       invisible wall around EVERY plot - students inside can't leave
#   nowalls     remove all plot walls (e.g. for the judging tour)
#   wall 3      wall around plot 3 only      nowall 3   remove it
#   (Teleport students into their plot first, e.g. /tp "Name" X -60 Z.
#    You can still walk through walls; students can't.)
#
# Map scale: 1 block is about 1.2 m. World position 0,0 is the Main Entry
# (Third Avenue end of the school). Stand on the ground when typing commands.
# If a block name gives an error in chat, change it in the BLOCK list.
# =====================================================================

